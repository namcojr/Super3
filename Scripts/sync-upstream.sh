#!/bin/bash
# Update Src/ to upstream Supermodel and refresh the files derived from it.
#
#   Scripts/sync-upstream.sh [path-to-supermodel-checkout] [commit]
#
# Src/ is never edited in this repository: Android code lives in
# android/app/src/main/cpp (override/ replaces upstream desktop-GL headers).
set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
UP=${1:-$REPO/../supermodel-upstream}
REV=${2:-origin/master}
ASSETS=$REPO/android/app/src/main/assets/Config
GEN=$REPO/android/app/src/main/cpp/generated

git -C "$UP" fetch -q origin
COMMIT=$(git -C "$UP" rev-parse --short "$REV")
echo "Syncing Src/ to upstream $COMMIT ($(git -C "$UP" log -1 --format=%cd --date=short "$REV"))"
echo "Upstream commits since last sync:"
[ -f "$REPO/UPSTREAM" ] && git -C "$UP" log --oneline --no-merges "$(cat "$REPO/UPSTREAM")..$REV" -- Src Config | sed 's/^/  /' || true

# 1. Source tree, byte for byte
rm -rf "$REPO/Src"
git -C "$UP" archive "$REV" Src | tar -x -C "$REPO"

# 2. Game database: Model 3 entries only (this build runs nothing else)
python3 -I - "$UP" "$REV" "$ASSETS/Games.xml" "$REPO/Config/Games.xml" <<'PY'
import re, subprocess, sys
up, rev, *outs = sys.argv[1:]
xml = subprocess.run(["git", "-C", up, "show", f"{rev}:Config/Games.xml"], capture_output=True, text=True, check=True).stdout.replace("\r\n", "\n")
games = list(re.finditer(r"[ \t]*<game\b.*?</game>\n", xml, re.S))
kept = [m.group(0) for m in games if "<platform>Sega Model 3</platform>" in m.group(0)]
out = xml[:games[0].start()] + "".join(kept) + xml[games[-1].end():]
for path in outs:
    open(path, "w").write(out)
print(f"Games.xml: kept {len(kept)} of {len(games)} games (Model 3 only)")
PY
git -C "$UP" show "$REV:Config/Music.xml" | sed 's/\r$//' > "$ASSETS/Music.xml"

# 3. Musashi 68K opcode tables (generated by a host tool from Src/)
TMP=$(mktemp -d)
cc -O1 -o "$TMP/m68kmake" "$REPO/Src/CPU/68K/Musashi/m68kmake.c"
"$TMP/m68kmake" "$GEN" "$REPO/Src/CPU/68K/Musashi/m68k_in.c" > /dev/null
rm -rf "$TMP"

# 4. Upstream's default settings, taken from the desktop front end (Main.cpp is
#    not built for Android). Key bindings are left out: SUPER3 sets its own.
python3 -I - "$REPO/Src/OSD/SDL/Main.cpp" "$GEN/UpstreamDefaultConfig.cpp" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8").read().replace("\r\n", "\n")
m = re.search(r"^Util::Config::Node DefaultConfig\(\)\n\{.*?^\}\n", src, re.S | re.M)
# Bindings are config.Set<std::string>("Input<Name>", ...); InputSystem is a setting.
is_binding = lambda l: re.search(r'config\.Set<std::string>\("Input(?!System")', l)
body = "\n".join(l for l in m.group(0).splitlines() if not is_binding(l))
body = body.replace("Util::Config::Node DefaultConfig()", "Util::Config::Node UpstreamDefaultConfig()", 1)
# Every key that is labelled or looked up must still be defined after filtering
defined = set(re.findall(r'config\.Set(?:<[^>]*>)?\(\s*(?:std::string\()?"([^"]+)"', body)) | set(re.findall(r'config\.SetEmpty\("([^"]+)"', body))
used = set(re.findall(r'SetLabels\("([^"]+)"', body)) | set(re.findall(r'config\["([^"]+)"\]', body))
if used - defined:
    sys.exit(f"UpstreamDefaultConfig: keys used but not defined after filtering: {sorted(used - defined)}")
out = f"""// GENERATED by Scripts/sync-upstream.sh from Src/OSD/SDL/Main.cpp DefaultConfig(). Do not edit.
#include <string>
#include <vector>
#include "Util/NewConfig.h"
#include "OSD/FileSystemPath.h"
#include "Network/NetProtocol.h"
#include "Inputs/InputSystem.h"

static const std::string s_gameXMLFilePath = "Config/Games.xml";

{body}
"""
open(sys.argv[2], "w").write(out)
print("UpstreamDefaultConfig.cpp generated")
PY

# 5. Audio output (Src/OSD/SDL/Audio.cpp) with Android changes. Each change must
#    match exactly once, so an upstream rewrite stops the sync instead of
#    silently dropping it.
python3 -I - "$REPO/Src/OSD/SDL/Audio.cpp" "$GEN/Audio_android.cpp" <<'PY'
import sys
src = open(sys.argv[1], encoding="utf-8").read().replace("\r\n", "\n")
changes = [
    # Android delivers audio in larger, less regular bursts than desktop systems
    # (44.1 kHz is resampled to the 48 kHz mixer, no fast track). 50 ms runs dry
    # now and then, and the multi-threaded sound board then replays old audio.
    ("static constexpr unsigned targetLatencyMs = 50;",
     "static constexpr unsigned targetLatencyMs = 100;  // SUPER3: 50 on upstream"),
    # Log under-runs: they are audible (stutter), so make them visible in logcat
    ("        underRuns++;\n\n        //printf(\"Audio buffer under-run #%u in PlayCallback",
     "        underRuns++;\n        SDL_Log(\"Audio under-run #%u (output callback)\", underRuns);\n\n        //printf(\"Audio buffer under-run #%u in PlayCallback"),
    ("        underRuns++;\n\n        //printf(\"Audio buffer under-run #%u in OutputAudio",
     "        underRuns++;\n        SDL_Log(\"Audio under-run #%u (sound board)\", underRuns);\n\n        //printf(\"Audio buffer under-run #%u in OutputAudio"),
]
for old, new in changes:
    n = src.count(old)
    if n != 1:
        sys.exit(f"Audio_android.cpp: expected 1 match, found {n}: {old[:70]!r}")
    src = src.replace(old, new)
open(sys.argv[2], "w").write("// GENERATED by Scripts/sync-upstream.sh from Src/OSD/SDL/Audio.cpp (see step 5). Do not edit.\n" + src)
print("Audio_android.cpp generated")
PY

# 6. New3D renderer (Src/Graphics/New3D/New3D.cpp) with per-frame geometry in
#    its own buffer. Upstream updates part of one ~144 MB vertex buffer every
#    frame; on Adreno the driver copies the whole buffer when the GPU is still
#    using it (~8 ms per frame, up to 35 ms). Same rule as step 5: each change
#    must match exactly once.
python3 -I - "$REPO/Src/Graphics/New3D" "$GEN/New3D_android.cpp" <<'PY'
import os, re, sys
srcdir, out = sys.argv[1:]
src = open(os.path.join(srcdir, "New3D.cpp"), encoding="utf-8").read().replace("\r\n", "\n")

def change(old, new):
    global src
    n = src.count(old)
    if n != 1:
        sys.exit(f"New3D_android.cpp: expected 1 match, found {n}: {old[:70]!r}")
    src = src.replace(old, new)

# Upstream's vertex attribute setup, reused for the per-frame buffer
m = re.search(r"\tglEnableVertexAttribArray\(m_r3dShader\.GetVertexAttribPos\(\"inVertex\"\)\);\n.*?\n\n\tglBindVertexArray\(0\);\n\tm_vbo\.Bind\(false\);\n\}\n", src, re.S)
if not m:
    sys.exit("New3D_android.cpp: vertex attribute setup not found")
attribs = m.group(0)[: m.group(0).index("\n\n\tglBindVertexArray(0);")] + "\n"

change("#define MAX_ROM_VERTS 1500000\n",
       "#define MAX_ROM_VERTS 1500000\n\n"
       "// SUPER3: per-frame (RAM) geometry lives in its own buffer, replaced every frame.\n"
       "// Meshes keep upstream's offsets: vboOffset >= MAX_ROM_VERTS means this buffer.\n"
       "static VBO    s_vboDyn;\n"
       "static GLuint s_vaoDyn = 0;\n")
change("\tglBindVertexArray(0);\n\tm_vbo.Bind(false);\n}\n\nCNew3D::~CNew3D()",
       "\tglBindVertexArray(0);\n\tm_vbo.Bind(false);\n\n"
       "\t// SUPER3: same vertex layout on the per-frame buffer\n"
       "\tglGenVertexArrays(1, &s_vaoDyn);\n\tglBindVertexArray(s_vaoDyn);\n"
       "\ts_vboDyn.Create(GL_ARRAY_BUFFER, GL_STREAM_DRAW, sizeof(FVertex) * MAX_RAM_VERTS);\n"
       "\ts_vboDyn.Bind(true);\n\n" + attribs +
       "\n\tglBindVertexArray(0);\n\ts_vboDyn.Bind(false);\n}\n\nCNew3D::~CNew3D()")
change("\tm_vbo.Destroy();\n\tif (m_vao) {",
       "\ts_vboDyn.Destroy();\t// SUPER3\n\tif (s_vaoDyn) {\n\t\tglDeleteVertexArrays(1, &s_vaoDyn);\n\t\ts_vaoDyn = 0;\n\t}\n\n"
       "\tm_vbo.Destroy();\n\tif (m_vao) {")
change("\tm_vbo.BufferSubData(MAX_ROM_VERTS*sizeof(FVertex), m_polyBufferRam.size()*sizeof(FVertex), m_polyBufferRam.data());",
       "\t// SUPER3: fresh storage every frame, so the driver neither waits for the GPU nor copies the big buffer\n"
       "\ts_vboDyn.Bind(true);\n"
       "\tglBufferData(GL_ARRAY_BUFFER, m_polyBufferRam.size()*sizeof(FVertex), m_polyBufferRam.data(), GL_STREAM_DRAW);\n"
       "\tm_vbo.Bind(true);")
change("\t\t\t\t\tglDrawArrays(m_primType, mesh.vboOffset, mesh.vertexCount);",
       "\t\t\t\t\tif (mesh.vboOffset >= MAX_ROM_VERTS) {\t// SUPER3: per-frame buffer\n"
       "\t\t\t\t\t\tglBindVertexArray(s_vaoDyn);\n"
       "\t\t\t\t\t\tglDrawArrays(m_primType, mesh.vboOffset - MAX_ROM_VERTS, mesh.vertexCount);\n"
       "\t\t\t\t\t}\n\t\t\t\t\telse {\n"
       "\t\t\t\t\t\tglBindVertexArray(m_vao);\n"
       "\t\t\t\t\t\tglDrawArrays(m_primType, mesh.vboOffset, mesh.vertexCount);\n"
       "\t\t\t\t\t}")
change("\t\t\t\tm_vbo.AppendData(size, &m_polyBufferRom[vboBytes / sizeof(FVertex)]);",
       "\t\t\t\t// SUPER3: appended past the used part of the buffer, which the GPU has never read,\n"
       "\t\t\t\t// so it needs no synchronisation (otherwise Adreno copies the whole buffer first)\n"
       "\t\t\t\tSuper3GLES_UnsynchronizedUploads(1);\n"
       "\t\t\t\tm_vbo.AppendData(size, &m_polyBufferRom[vboBytes / sizeof(FVertex)]);\n"
       "\t\t\t\tSuper3GLES_UnsynchronizedUploads(0);")

# The copy is compiled outside Src/Graphics/New3D: point its local includes there
local = set(os.listdir(srcdir))
src = re.sub(r'#include "([^"/]+)"', lambda m: f'#include "Graphics/New3D/{m.group(1)}"' if m.group(1) in local else m.group(0), src)
open(out, "w").write("// GENERATED by Scripts/sync-upstream.sh from Src/Graphics/New3D/New3D.cpp (see step 6). Do not edit.\n" + src)
print("New3D_android.cpp generated")
PY

# 7. Texture uploads (Src/Graphics/New3D/TextureBank.cpp): one glTexSubImage2D
#    per rectangle instead of one per row. Rows are 2048 texels apart in texture
#    RAM; a burst of new textures made ~29000 calls (400 ms) in one second.
python3 -I - "$REPO/Src/Graphics/New3D" "$GEN/TextureBank_android.cpp" <<'PY'
import os, re, sys
srcdir, out = sys.argv[1:]
src = open(os.path.join(srcdir, "TextureBank.cpp"), encoding="utf-8").read().replace("\r\n", "\n")
old = ("\tfor (int i = 0; i < height; i++) {\n"
       "\t\tglTexSubImage2D(GL_TEXTURE_2D, level, subX, subY + i, width, 1, GL_RED_INTEGER, GL_UNSIGNED_SHORT, m_textureRam + ((y + i) * 2048) + x);\n"
       "\t}\n")
new = ("\t// SUPER3: whole rectangle in one call; texture RAM rows are 2048 texels apart\n"
       "\tglPixelStorei(GL_UNPACK_ROW_LENGTH, 2048);\n"
       "\tglTexSubImage2D(GL_TEXTURE_2D, level, subX, subY, width, height, GL_RED_INTEGER, GL_UNSIGNED_SHORT, m_textureRam + (y * 2048) + x);\n"
       "\tglPixelStorei(GL_UNPACK_ROW_LENGTH, 0);\n")
if src.count(old) != 1:
    sys.exit(f"TextureBank_android.cpp: expected 1 match, found {src.count(old)}")
src = src.replace(old, new)
local = set(os.listdir(srcdir))
src = re.sub(r'#include "([^"/]+)"', lambda m: f'#include "Graphics/New3D/{m.group(1)}"' if m.group(1) in local else m.group(0), src)
open(out, "w").write("// GENERATED by Scripts/sync-upstream.sh from Src/Graphics/New3D/TextureBank.cpp (see step 7). Do not edit.\n" + src)
print("TextureBank_android.cpp generated")
PY

echo "$COMMIT" > "$REPO/UPSTREAM"
echo "Done. Review 'git status', build, test, commit."
